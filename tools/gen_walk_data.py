#!/usr/bin/env python3
"""Generate web/js/walk-data.js: the per-character idle-wander table.

The engine's idle wander (notes/13 "Idle wander RE") reads two things out of
each <Character> definition that the viewer needs to replicate it:

  <WalkSpeed speed="50" />                 per-character walk speed
  <MovementBehavior mode="RandomRelaxed">  the behaviour enum (parser
        libscorpio.so 0xec0808 stores it at behaviour struct +0x4c; the enum
        is 0 Invalid, 1 RandomRelaxed, 2 RandomRush, 3 RandomHover,
        4 JobLocation, 5 JobLocationHover, 6 JobLocationWaitForScript,
        7 Scripted, 8 Idle, 9 Sneak, 10 RushAndRest, 11 CenterScreen)

Only 46 of the 412 shipped characters name a mode, so the port's DEFAULT is
RandomRelaxed (what plain characters like Homer get) and the table below only
carries the exceptions plus the speeds.

Inputs (all project-local):
  data/character_ids.json                  save id -> character name
  web/assets/dlc/gamescripts-r*/data/*characters*.xml
        every gamescripts pack, newest revision first (a name defined in more
        than one pack takes the newest definition)

Output:
  web/js/walk-data.js        window.WALK_DATA = {version, generated, source,
                             defaults, chars: {save id: {speed, mode}}}

Regenerate after pulling a new gamescripts pack:
  python3 tools/gen_walk_data.py
"""
import glob
import json
import os
import re
import sys
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DLC = os.path.join(ROOT, 'web', 'assets', 'dlc')
OUT = os.path.join(ROOT, 'web', 'js', 'walk-data.js')

CHAR_RE = re.compile(r'<Character\s+([^>]*)>(.*?)</Character>', re.S)
NAME_RE = re.compile(r'\bname="([^"]+)"')
SPEED_RE = re.compile(r'<WalkSpeed\s+[^>]*\bspeed="([\d.]+)"')
MODE_RE = re.compile(r'<MovementBehavior\b[^>]*\bmode="([^"]+)"')

# The engine's own defaults (settings.xml, gamescripts-r343174):
# <WalkDefaultSpeeds slow="0.9" fast="2.0" /> is the tiles/second bracket the
# per-character WalkSpeed is clamped into, and 50 is the shipped median speed.
DEFAULTS = {'speed': 50, 'slow': 0.9, 'fast': 2.0, 'mode': 'RandomRelaxed'}


def packs():
    """gamescripts packs, newest revision first."""
    out = []
    for d in glob.glob(os.path.join(DLC, 'gamescripts-r*')):
        m = re.search(r'gamescripts-r(\d+)$', d)
        if m and os.path.isdir(os.path.join(d, 'data')):
            out.append((int(m.group(1)), d))
    return [d for _r, d in sorted(out, reverse=True)]


def harvest():
    """name -> {speed, mode}, newest pack wins (first seen)."""
    table, src = {}, {}
    for pack in packs():
        for f in glob.glob(os.path.join(pack, 'data', '*characters*.xml')):
            try:
                s = open(f, encoding='utf-8', errors='replace').read()
            except OSError:
                continue
            for m in CHAR_RE.finditer(s):
                nm = NAME_RE.search(m.group(1))
                if not nm:
                    continue
                name = nm.group(1)
                if name in src:
                    continue                        # a newer pack already spoke
                body = m.group(2)
                sp = SPEED_RE.search(body)
                md = MODE_RE.search(body)
                if not sp and not md:
                    continue
                rec = {}
                if sp:
                    rec['speed'] = float(sp.group(1))
                if md:
                    rec['mode'] = md.group(1)
                table[name] = rec
                src[name] = os.path.relpath(f, ROOT)
    return table, src


def main():
    ids = json.load(open(os.path.join(ROOT, 'data', 'character_ids.json')))
    table, src = harvest()
    chars, miss = {}, 0
    for cid, name in ids.items():
        rec = table.get(name)
        if not rec:
            miss += 1
            continue
        out = {}
        if rec.get('speed') is not None:
            out['speed'] = rec['speed']
        if rec.get('mode'):
            out['mode'] = rec['mode']
        if out:
            chars[cid] = out
    payload = {
        'version': 1,
        'generated': date.today().isoformat(),
        'source': 'gamescripts-r*/data/*characters*.xml <WalkSpeed>/'
                  '<MovementBehavior mode>',
        'defaults': DEFAULTS,
        'chars': chars,
    }
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write('/* walk-data.js — per-character idle-wander table, GENERATED by\n'
                 '   tools/gen_walk_data.py (do not hand-edit). One entry per save\n'
                 '   character id: speed = the XML <WalkSpeed speed>, mode = the\n'
                 '   <MovementBehavior mode> enum; a character with no entry gets\n'
                 '   defaults (speed 50, RandomRelaxed) — the engine-side default\n'
                 '   the plain characters like Homer ship without. notes/13. */\n')
        fh.write('window.WALK_DATA = ')
        json.dump(payload, fh, separators=(',', ':'))
        fh.write(';\n')
    print(f'  {len(chars)} of {len(ids)} save characters carry walk data '
          f'({miss} fall back to the defaults)')
    print(f'  -> {os.path.relpath(OUT, ROOT)} '
          f'({os.path.getsize(OUT) / 1024:.1f} KB)')


if __name__ == '__main__':
    sys.exit(main())
