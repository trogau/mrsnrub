#!/usr/bin/env python3
"""
Boot explorer data generator (M5.1b).

Inputs (all project-local):
    web/assets/boot/boot-manifest.json   produced by tools/extract_boot_assets.py

Output:
    web/js/boot-explorer-data.js   window.BOOT_DATA = {...}  (a few hundred KB,
                                   no network) — inlined by
                                   web/boot-explorer.html so the page works
                                   from file:// like the game itself.

Run tools/extract_boot_assets.py first (or whenever the boot set changes).

Usage:
    python3 tools/gen_boot_explorer.py [--assets web/assets] [--js web/js]
"""

import argparse
import json
import os
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument('--assets', default=os.path.join(REPO_ROOT, 'web', 'assets'))
    ap.add_argument('--js', default=os.path.join(REPO_ROOT, 'web', 'js'))
    args = ap.parse_args()

    src = os.path.join(args.assets, 'boot', 'boot-manifest.json')
    try:
        with open(src) as f:
            manifest = json.load(f)
    except FileNotFoundError:
        print('no %s — run tools/extract_boot_assets.py first' % src,
              file=sys.stderr)
        return 1

    out = os.path.join(args.js, 'boot-explorer-data.js')
    with open(out, 'w') as f:
        f.write('/* GENERATED by tools/gen_boot_explorer.py — do not edit by hand.\n')
        f.write('   Boot-screen asset inventory (cdn/ bundles + APK side),\n')
        f.write('   generated %s by %s. */\n'
                % (manifest.get('generated', '?'), manifest.get('tool', '?')))
        f.write('window.BOOT_DATA = ')
        json.dump(manifest, f, separators=(',', ':'))
        f.write(';\n')
    print('wrote %s (%d files, %d KB)'
          % (os.path.relpath(out, REPO_ROOT), len(manifest.get('files', [])),
             os.path.getsize(out) // 1024))
    return 0


if __name__ == '__main__':
    sys.exit(main())
