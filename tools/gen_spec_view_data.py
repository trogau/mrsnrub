#!/usr/bin/env python3
"""Generate web/viewer/spec-view-data.js from road-spec.json.

The spec viewer renders ONLY what road-spec.json defines (the ground
truth road layer extracted from the .pb save) — no MAP_DATA, no other
layers. This tool embeds the grid as a plain JS array so the page works
over file:// (fetch of ../../road-spec.json would be CORS-blocked).

Rows the spec file truncated (147 chars instead of 148) are re-padded
with 'G'; the char histogram is checked against the spec's own
road_layer_stats before writing.

Regenerate after any change to road-spec.json:
    python3 tools/gen_spec_view_data.py
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
spec = json.loads((root / 'road-spec.json').read_text())

rows = spec['road_data']['grid_rows_ascii']
width = max(len(r) for r in rows)
rows = [r.ljust(width, 'G') for r in rows]        # re-pad truncated rows

hist = {}
for r in rows:
    for ch in r:
        if ch != 'G':
            hist[ch] = hist.get(ch, 0) + 1
want = dict(spec['road_layer_stats']['char_histogram'])
assert hist == want, f'histogram mismatch:\n {hist}\n {want}'

gc = spec['tile_layout']['grid_cells']
assert width == gc['cols'] and len(rows) == gc['rows'], \
    f'grid {width}x{len(rows)} != spec {gc["cols"]}x{gc["rows"]}'

out = {
    'source': 'road-spec.json (road layer of the .pb save; ground truth)',
    'cell_ox': 0, 'cell_oy': -112,     # tile-exact origin: walk/building-oracle sweep 2026-10-25 (block part = (-3,-7)x16)
    'cell_stride': 37,                 # blocks per block-row (reciprocity 1.000)
    'cols': width, 'rows': len(rows),
    'grid': rows,
}

dst = root / 'web' / 'viewer' / 'spec-view-data.js'
dst.write_text(
    '/* GENERATED by tools/gen_spec_view_data.py — do not edit by hand.\n'
    '   Source: road-spec.json, histogram-verified against its\n'
    '   road_layer_stats.char_histogram. Regenerate with\n'
    '   `python3 tools/gen_spec_view_data.py` after editing the spec. */\n'
    'window.ROAD_SPEC = ' + json.dumps(out) + ';\n')
print(f'wrote {dst}  grid {width}x{len(rows)}  '
      f'nonempty {sum(hist.values())} chars')
