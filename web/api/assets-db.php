<?php
/* assets-db.php — shared SQLite access for the Asset Explorer API
   (web/api/assets.php) and page (web/assets-explorer.php). The database is
   generated by tools/build_assets_db.php from the extraction manifest. */
declare(strict_types=1);

function assets_db_path(): string {
    return getenv('ASSETS_DB') ?: __DIR__ . '/assets.sqlite';
}

function assets_db(): PDO {
    $db = assets_db_path();
    if (!is_file($db)) {
        throw new RuntimeException(
            'assets database missing — run: php tools/build_assets_db.php');
    }
    return new PDO('sqlite:' . $db, null, null, [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
    ]);
}

const ASSETS_ENTRY_COLS = 'a.path, a.base, a.type, a.cat,'
    . ' s.name AS source, a.origin, a.family, a.res_class, a.kind,'
    . ' a.bytes, a.w, a.h, a.duration_s, a.channels, a.sample_rate,'
    . ' a.codec, a.vcodec, a.acodec, a.audio_format, a.bpp, a.premul,'
    . ' a.anchor, a.thumb, a.char, a.animation, a.n_cells, a.n_frames,'
    . ' a.frames, a.strings, a.decode_error,'
    . ' p.pack, p.season, p.tier, p.revision, p.url, p.index_version';

function assets_entry_sel(string $extraCols = ''): string {
    return 'SELECT ' . ($extraCols !== '' ? $extraCols . ', ' : '')
        . ASSETS_ENTRY_COLS
        . ' FROM assets a'
        . ' LEFT JOIN sources s ON s.id = a.source_id'
        . ' LEFT JOIN packs   p ON p.id = a.pack_id';
}

/* Rebuild a manifest entry (the JSON shape the browser explorer and the
   game modules expect) from a joined row. */
function assets_entry(?array $r): ?array {
    if ($r === null) { return null; }
    $e = array_filter([
        'path' => $r['path'], 'type' => $r['type'],
        'source' => $r['source'], 'origin' => $r['origin'],
        'family' => $r['family'], 'resClass' => $r['res_class'],
        'kind' => $r['kind'], 'bytes' => $r['bytes'],
        'w' => $r['w'], 'h' => $r['h'], 'duration_s' => $r['duration_s'],
        'channels' => $r['channels'], 'sample_rate' => $r['sample_rate'],
        'codec' => $r['codec'], 'vcodec' => $r['vcodec'],
        'acodec' => $r['acodec'], 'audio_format' => $r['audio_format'],
        'bpp' => $r['bpp'], 'thumb' => $r['thumb'],
        'char' => $r['char'], 'animation' => $r['animation'],
        'n_cells' => $r['n_cells'], 'n_frames' => $r['n_frames'],
        'strings' => $r['strings'], 'decode_error' => $r['decode_error'],
    ], fn($v) => $v !== null && $v !== '');
    if ($r['premul'] !== null) { $e['premul'] = $r['premul'] === '1'; }
    if ($r['anchor'] !== null) { $e['anchor'] = json_decode($r['anchor'], true); }
    if ($r['frames'] !== null) { $e['frames'] = json_decode($r['frames'], true); }
    if ($r['pack'] !== null) {
        $e['dlc'] = array_filter([
            'pack' => $r['pack'], 'season' => $r['season'],
            'tier' => $r['tier'], 'revision' => $r['revision'],
            'url' => $r['url'], 'indexVersion' => $r['index_version'],
        ], fn($v) => $v !== null && $v !== '');
    }
    return $e;
}
