/* map-explorer.js — interactive schematic city map.
   Classic script, no modules, no build, no network.
   Data: window.MAP_DATA from js/map-explorer-data.js
   (generated by tools/gen_map_explorer.py).

   World model (town tiles, verified — notes/01-binary-formats.md):
     terrain grid 512 wide, 16-char records, codebook a..p = one tile at
     offset c-'a', G = none, P = all 16;  town = grid - (OX, OY)
     building rect: X [posX-locX+1 .. posX-locX+x], Y [posY-locY+1 .. posY-locY+z]
   One world px = S (2) per tile; the #world div is scaled for pan/zoom. */
'use strict';

const D = window.MAP_DATA;
const OX = D.ox, OY = D.oy;
const TX0 = D.tx0, TY0 = D.ty0, S = D.s;
const GW = D.gw, GH = D.gh;
const trackSet = new Set(D.tracks);
const hidden = new Set();   // legend keys toggled off: 'grass', layer names, 'bld', 'track', 'chars'
const rgb = c => `rgb(${c[0]},${c[1]},${c[2]})`;
const esc = s => String(s).replace(/[&<>"']/g,
    c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const $ = id => document.getElementById(id);

/* ================= terrain (canvas, drawn once) ============================= */

function decodeTiles(str, vert) {
    // returns flat [x0, y0, x1, y1, ...] grid coords.
    // Normal layers: char i = 16 sub-columns along x of row y=i/32.
    // The sea patch (3072-char oceanData frame) is COLUMN-major
    // (vert): char i = 16 sub-cells along y of column x=i/32 — the sea
    // runs as a vertical strip down the left edge (see terrain.js).
    const out = [];
    const perRow = 32; // grid width 512 / 16-char records
    for (let i = 0; i < str.length; i++) {
        const c = str.charCodeAt(i);
        if (c === 0x47) continue;              // 'G' -> no tile
        const r = (i / perRow) | 0, x0 = (i % perRow) * 16;
        if (c === 0x50) {                       // 'P' -> all 16
            for (let k = 0; k < 16; k++) { if (vert) out.push(r, x0 + k); else out.push(x0 + k, r); }
        } else {
            const k = c - 0x61;                 // 'a'..'p'
            if (k >= 0 && k < 16) { if (vert) out.push(r, x0 + k); else out.push(x0 + k, r); }
        }
    }
    return out;
}

function drawTerrain() {
    const cv = $('terrain');
    cv.width = GW; cv.height = GH;   // re-assign clears previous paint
    const ctx = cv.getContext('2d');
    if (!hidden.has('grass')) {
        ctx.fillStyle = rgb(D.grass);
        ctx.fillRect(0, 0, GW, GH);
    }
    for (const L of D.layers) {
        if (hidden.has(L.n)) continue;
        ctx.fillStyle = rgb(L.c);
        let t, off;
        if (L.pts) {                       // brush layers: pre-decoded grid pts
            t = L.pts; off = 0;
        } else {
            const vert = L.s.length === 3072;  // sea-patch frame (column-major)
            t = decodeTiles(L.s, vert);
            off = vert ? -33 : 0;              // sea sits west of grid x=0 (see terrain.js)
        }
        for (let i = 0; i < t.length; i += 2) {
            const px = (t[i] + off - OX - TX0) * S;
            const py = (t[i + 1] - OY - TY0) * S;
            if (px < -S || py < -S || px >= GW || py >= GH) continue;
            ctx.fillRect(px, py, S, S);
        }
    }
}

/* ================= map objects (HTML overlay) =============================== */

const bwrap = $('bwrap');
const world = $('world');
world.style.width = GW + 'px';
world.style.height = GH + 'px';

const bEls = [];   // index-aligned with D.buildings
const cEls = [];   // index-aligned with D.chars
const frag = document.createDocumentFragment();

for (let i = 0; i < D.buildings.length; i++) {
    const [id, x0, y0, w, h, fs, px, py] = D.buildings[i];
    const e = D.binfo[id];
    const el = document.createElement('div');
    el.className = 'bld' + (trackSet.has(id) ? ' track' : '');
    el.style.left = (x0 - TX0) * S + 'px';
    el.style.top = (y0 - TY0) * S + 'px';
    el.style.width = w * S + 'px';
    el.style.height = h * S + 'px';
    el.style.background = trackSet.has(id) ? rgb(D.trackcol) : rgb(D.pal[id % D.pal.length]);
    const name = e ? e[0] : 'unknown #' + id;
    el.dataset.tip = `${name} — #${id} · ${w}×${h} @ (${px},${py})` +
        (fs ? ` · flip ${fs}` : '');
    el.dataset.bi = i;
    bEls.push(el);
    frag.appendChild(el);
}

const CHAR_D = 6; // dot size at base scale (world px)
for (let i = 0; i < D.chars.length; i++) {
    const [id, x, y] = D.chars[i];
    const el = document.createElement('div');
    el.className = 'char';
    el.style.left = ((x - TX0) * S + S / 2 - CHAR_D / 2) + 'px';
    el.style.top = ((y - TY0) * S + S / 2 - CHAR_D / 2) + 'px';
    el.style.width = CHAR_D + 'px';
    el.style.height = CHAR_D + 'px';
    const name = D.charNames[id] || 'char #' + id;
    el.dataset.tip = `${name} (char #${id}) @ (${x},${y})`;
    el.dataset.ci = i;
    cEls.push(el);
    frag.appendChild(el);
}
bwrap.appendChild(frag);

/* ================= layer visibility (legend toggles) ========================= */

function applyVisibility() {
    for (const el of bEls) {
        el.classList.toggle('eloff',
            hidden.has(el.classList.contains('track') ? 'track' : 'bld'));
    }
    for (const el of cEls) el.classList.toggle('eloff', hidden.has('chars'));
    if (pin && pin.classList.contains('eloff')) setPin(null);
}

/* ================= details pane ============================================= */

const details = $('details');
const PLACEHOLDER = '<div class="placeholder">Hover a building or character&hellip;</div>';
let pin = null;      // pinned element

function buildingHtml(i) {
    const [id, x0, y0, w, h, fs, px, py] = D.buildings[i];
    const e = D.binfo[id];
    if (!e) return `<h3>unknown</h3><p class="dim">No catalog entry for #${id}.</p>`;
    const [name, asset, slug, x, z, locX, locY, height, via, count] = e;
    const viaCls = via === 'asset' ? 'via-asset' :
        (via === 'flip' || via === 'rotated') ? 'via-flip' : 'via-other';
    return `
      <h3>${esc(name)}</h3>
      <div class="tagrow">
        <span class="tag">building <b>#${id}</b></span>
        <span class="tag"><b>${count}</b>&times; in save</span>
        ${fs ? `<span class="tag">flip state <b>${fs}</b></span>` : ''}
      </div>
      <table>
        <tr><td>asset</td><td>${esc(asset)}</td></tr>
        <tr><td>slug</td><td>${esc(slug)}</td></tr>
        <tr><td>footprint</td><td>${w} &times; ${h} tiles (drawn)</td></tr>
        <tr><td>catalog dims</td><td>${x} &times; ${z}, anchor ${locX}, ${locY}</td></tr>
        <tr><td>height</td><td>${height}</td></tr>
        <tr><td>position</td><td>${px}, ${py}</td></tr>
        <tr><td>covers tiles</td><td>X ${Math.round(x0)}..${Math.round(x0 + w - 1)},
            Y ${Math.round(y0)}..${Math.round(y0 + h - 1)}</td></tr>
        <tr><td>resolved via</td><td class="${viaCls}">${esc(via)}</td></tr>
      </table>
      ${pin === bEls[i] ? '<div class="pinnote">Pinned — Esc or click the background to unpin.</div>' : ''}`;
}

function charHtml(i) {
    const [id, x, y] = D.chars[i];
    const name = D.charNames[id];
    const count = D.chars.filter(c => c[0] === id).length;
    return `
      <h3>${esc(name || 'char #' + id)}</h3>
      <div class="tagrow">
        <span class="tag">character <b>#${id}</b></span>
        <span class="tag"><b>${count}</b>&times; in save</span>
      </div>
      <table>
        <tr><td>position</td><td>${x}, ${y}</td></tr>
        <tr><td>name resolved</td><td>${name ? 'yes (character catalog)' : 'no'}</td></tr>
      </table>
      ${pin === cEls[i] ? '<div class="pinnote">Pinned — Esc or click the background to unpin.</div>' : ''}`;
}

function showEl(el) {
    if (!el) { details.innerHTML = PLACEHOLDER; return; }
    details.innerHTML = el.classList.contains('char')
        ? charHtml(+el.dataset.ci)
        : buildingHtml(+el.dataset.bi);
    // sprite-variant strip (transimage/menu/holo siblings of the asset's
    // slug) — DOM-appended from the shared renderer, not string HTML
    if (!el.classList.contains('char') && window.AssetVariants) {
        const e = D.binfo[D.buildings[+el.dataset.bi][0]];
        const v = AssetVariants.render(e && e[2]);
        if (v) details.appendChild(v);
    }
}

function onHover(el) {
    showEl(el || pin);
}

bwrap.addEventListener('mouseover', e => {
    const t = e.target.closest('.bld, .char');
    if (t) showEl(t);
});
bwrap.addEventListener('mouseleave', () => onHover(null));

function setPin(el) {
    if (pin) pin.classList.remove('sel');
    pin = el;
    if (pin) { pin.classList.add('sel'); }
    onHover(pin);
}

/* ================= pan / zoom =============================================== */

const stage = $('stage');
const V = { s: 1, tx: 0, ty: 0 };
const S_MIN = 0.2, S_MAX = 10;

function apply() {
    world.style.transform =
        `translate(${V.tx}px,${V.ty}px) scale(${V.s})`;
}

function stageRect() { return stage.getBoundingClientRect(); }

function fitRect(x, y, w, h) {
    const st = stageRect();
    const s = Math.min(S_MAX, Math.max(S_MIN,
        0.95 * Math.min(st.width / w, st.height / h)));
    V.s = s;
    V.tx = st.width / 2 - (x + w / 2) * s;
    V.ty = st.height / 2 - (y + h / 2) * s;
    apply();
}

function fitAll() { fitRect(0, 0, GW, GH); }

function fitDowntown() {
    const [x0, x1, y0, y1] = D.downtown[0];
    fitRect((x0 - TX0) * S, (y0 - TY0) * S, (x1 - x0) * S, (y1 - y0) * S);
}

function elRect(el) {
    return [el.offsetLeft, el.offsetTop, el.offsetWidth, el.offsetHeight];
}

function centerEl(el, minZoom) {
    const [x, y, w, h] = elRect(el);
    const st = stageRect();
    const s = Math.min(S_MAX, Math.max(minZoom || 2,
        0.4 * Math.min(st.width / w, st.height / h)));
    V.s = s;
    V.tx = st.width / 2 - (x + w / 2) * s;
    V.ty = st.height / 2 - (y + h / 2) * s;
    apply();
}

function zoomAt(sx, sy, f) {
    const ns = Math.min(S_MAX, Math.max(S_MIN, V.s * f));
    const f2 = ns / V.s;
    V.tx = sx - (sx - V.tx) * f2;
    V.ty = sy - (sy - V.ty) * f2;
    V.s = ns;
    apply();
    markViewCustom();
}

let downX = 0, downY = 0, lastX = 0, lastY = 0, moved = false, down = false;

stage.addEventListener('pointerdown', e => {
    if (e.button !== 0) return;
    down = true; moved = false;
    downX = lastX = e.clientX; downY = lastY = e.clientY;
    stage.setPointerCapture(e.pointerId);
});
stage.addEventListener('pointermove', e => {
    if (!down) return;
    const dx = e.clientX - lastX, dy = e.clientY - lastY;
    if (!moved && Math.hypot(e.clientX - downX, e.clientY - downY) > 3) {
        moved = true;
        stage.classList.add('panning');
    }
    if (moved) {
        V.tx += dx; V.ty += dy;
        lastX = e.clientX; lastY = e.clientY;
        apply();
        markViewCustom();
    }
});
stage.addEventListener('pointerup', () => {
    down = false;
    stage.classList.remove('panning');
});
stage.addEventListener('wheel', e => {
    e.preventDefault();
    const st = stageRect();
    zoomAt(e.clientX - st.left, e.clientY - st.top, Math.exp(-e.deltaY * 0.0015));
}, { passive: false });
stage.addEventListener('dblclick', e => {
    const st = stageRect();
    zoomAt(e.clientX - st.left, e.clientY - st.top, 2);
});

stage.addEventListener('click', e => {
    if (moved) return; // was a drag
    const t = e.target.closest('.bld, .char');
    if (t) setPin(t === pin ? null : t);
    else setPin(null);
});

function markViewCustom() {
    $('btn-full').classList.remove('on');
    $('btn-downtown').classList.remove('on');
}

$('btn-full').addEventListener('click', () => {
    fitAll();
    $('btn-full').classList.add('on');
    $('btn-downtown').classList.remove('on');
});
$('btn-downtown').addEventListener('click', () => {
    fitDowntown();
    $('btn-downtown').classList.add('on');
    $('btn-full').classList.remove('on');
});
$('btn-reset').addEventListener('click', () => {
    fitAll();
    setPin(null);
    search.value = '';
    doSearch();
    $('btn-full').classList.add('on');
    $('btn-downtown').classList.remove('on');
});

window.addEventListener('keydown', e => {
    if (document.activeElement === search && e.key !== 'Escape') return;
    const nudge = 40;
    if (e.key === 'Escape') { setPin(null); return; }
    if (e.key === 'ArrowLeft') { V.tx += nudge; apply(); markViewCustom(); e.preventDefault(); }
    if (e.key === 'ArrowRight') { V.tx -= nudge; apply(); markViewCustom(); e.preventDefault(); }
    if (e.key === 'ArrowUp') { V.ty += nudge; apply(); markViewCustom(); e.preventDefault(); }
    if (e.key === 'ArrowDown') { V.ty -= nudge; apply(); markViewCustom(); e.preventDefault(); }
});

/* ================= search ==================================================== */

const search = $('search');
const matchinfo = $('matchinfo');
let matches = [];
let searchTimer = null;

search.addEventListener('input', () => {
    clearTimeout(searchTimer);
    searchTimer = setTimeout(doSearch, 120);
});
search.addEventListener('keydown', e => {
    if (e.key === 'Enter' && matches.length) {
        centerEl(matches[0], 2);
        e.preventDefault();
    }
    if (e.key === 'Escape') { search.value = ''; doSearch(); }
    e.stopPropagation();
});

function doSearch() {
    const q = search.value.trim().toLowerCase();
    matches = [];
    for (const el of bEls) el.classList.remove('hl');
    for (const el of cEls) el.classList.remove('hl');
    if (!q) {
        bwrap.classList.remove('dimmed');
        matchinfo.textContent = '';
        return;
    }
    for (let i = 0; i < D.buildings.length; i++) {
        if (bEls[i].classList.contains('eloff')) continue;   // layer hidden
        const b = D.buildings[i];
        const e = D.binfo[b[0]];
        const hay = e ? (e[0] + ' ' + (e[1] || '') + ' ' + (e[2] || '')).toLowerCase() : '';
        if (q === String(b[0]) || hay.includes(q)) {
            bEls[i].classList.add('hl');
            matches.push(bEls[i]);
        }
    }
    for (let i = 0; i < D.chars.length; i++) {
        if (cEls[i].classList.contains('eloff')) continue;   // layer hidden
        const c = D.chars[i];
        const nm = (D.charNames[c[0]] || '').toLowerCase();
        if (q === String(c[0]) || nm.includes(q)) {
            cEls[i].classList.add('hl');
            matches.push(cEls[i]);
        }
    }
    bwrap.classList.add('dimmed');
    matchinfo.textContent = `${matches.length} match${matches.length === 1 ? '' : 'es'}` +
        (matches.length ? ' — Enter centers first' : '');
}

/* ================= legend + stats =========================================== */

/* Every legend row with a data-key is a show/hide toggle for its layer:
   grass / terrain layer names redraw the canvas; bld / track / chars hide
   the matching overlay divs. Rows keep a data-tip naming the action
   (project tooltip convention — no title attribute). */

function toggleRow(r) {
    const key = r.dataset.key;
    const off = !hidden.has(key);
    if (off) hidden.add(key); else hidden.delete(key);
    r.classList.toggle('off', off);
    r.dataset.tip = (off ? 'show ' : 'hide ') + (r.dataset.label || '');
    drawTerrain();        // cheap at 1400×1890; keeps grass/layer keys uniform
    applyVisibility();
}

function buildLegend() {
    const rows = [];
    const row = (key, swatch, label) =>
        `<span class="row" data-key="${esc(key)}" data-label="${esc(label)}"` +
        ` role="button" tabindex="0"` +
        ` data-tip="${hidden.has(key) ? 'show' : 'hide'} ${esc(label)}">` +
        `<span class="sw" style="background:${swatch}"></span>${esc(label)}</span>`;
    const sw = (key, c, label) => row(key, rgb(c), label);
    rows.push(sw('grass', D.grass, 'grass'));
    for (const L of D.layers) rows.push(sw(L.n, L.c, L.n));
    rows.push(row('bld',
        'linear-gradient(90deg,' + D.pal.map(rgb).join(',') + ')', 'buildings'));
    rows.push(sw('track', D.trackcol, 'mono rail'));
    rows.push(sw('chars', D.charcol, 'characters'));
    rows.push('<span class="row note" style="grid-column:1/3;color:var(--text-dim)">' +
        'block colour = building id mod 10 (palette, not type) &middot; ' +
        'click a swatch to toggle it</span>');
    $('legend').innerHTML = rows.join('');
}

const legend = $('legend');
legend.addEventListener('pointerdown', e => e.stopPropagation()); // no pan-drag from legend
legend.addEventListener('click', e => {
    const r = e.target.closest && e.target.closest('.row');
    if (!r || !r.dataset.key) return;
    e.stopPropagation();           // don't unpin / select through the legend
    toggleRow(r);
});
legend.addEventListener('keydown', e => {
    if (e.key !== 'Enter' && e.key !== ' ') return;
    const r = e.target.closest && e.target.closest('.row');
    if (!r || !r.dataset.key) return;
    e.preventDefault();
    e.stopPropagation();
    toggleRow(r);
});

function buildStats() {
    const nb = D.buildings.length;
    const nc = D.chars.length;
    const named = Object.keys(D.binfo).length;
    $('statsbar').innerHTML =
        `<b>${nb.toLocaleString()}</b> buildings · <b>${named.toLocaleString()}</b> named ids · ` +
        `<b>${nc}</b> characters · 100% resolved`;
}

/* ================= boot ======================================================= */

drawTerrain();
buildLegend();
buildStats();
requestAnimationFrame(fitAll);
