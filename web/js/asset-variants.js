/* asset-variants.js — shared "sprite variants" strip for the details
   cards on the map pages (Map Explorer + City View).

   MAP_DATA.variants[slug] (generated by tools/gen_map_explorer.py) lists
   the extra sprites an asset ships: the main art, its <slug>_transimage
   alpha sidecar, the <slug>_menu build-menu thumbnail, <slug>_holo event
   variants, <slug>_flipped copies — one representative per kind. Static
   tiles render as a clickable thumbnail grid; each opens the Asset
   Explorer on that file (?path= deep link). Rows with kind 'anim' are
   bsv3 named-anim filmstrip atlases (tools/gen_city_sprites.py anims):
   they play in place on a canvas, with play/pause, a speed toggle, and —
   when the asset has several named loops — a button per loop. Pure DOM,
   no fetch, works from file:// like the pages themselves. */
(function (global) {
    'use strict';

    var players = [];        // live anim players (stopped on every render)

    function renderVariants(slug) {
        var V = (global.MAP_DATA && global.MAP_DATA.variants) || {};
        var list = V[String(slug || '').toLowerCase()];
        stopPlayers();
        if (!list || !list.length) { return null; }

        var box = document.createElement('div');
        box.className = 'variants';
        var label = document.createElement('div');
        label.className = 'vlabel';
        label.textContent = 'Sprite variants — ' + list.length;
        box.appendChild(label);

        var row = document.createElement('div');
        row.className = 'vrow';
        for (var i = 0; i < list.length; i++) {
            row.appendChild(list[i].kind === 'anim'
                ? animTile(list[i]) : tile(list[i]));
        }
        box.appendChild(row);
        return box;
    }

    function stopPlayers() {
        for (var i = 0; i < players.length; i++) players[i].stop();
        players = [];
    }

    function tile(v) {
        var name = v.path.split('/').pop();
        var t = document.createElement('a');
        t.className = 'vtile';
        t.href = 'assets-explorer.php?path=' + encodeURIComponent(v.path);
        t.dataset.tip = name + ' · ' + v.kind +
            (v.res ? ' · ' + v.res : '') +
            (v.w != null ? ' · ' + v.w + '×' + v.h : '') +
            ' — open in Asset Explorer';

        var pic = document.createElement('div');
        pic.className = 'vpic';
        var img = document.createElement('img');
        img.loading = 'lazy';
        img.decoding = 'async';
        img.src = 'assets/' + v.path;
        img.alt = name;
        pic.appendChild(img);
        t.appendChild(pic);

        var bits = [v.kind];
        if (v.res) { bits.push(v.res); }
        if (v.w != null) { bits.push(v.w + '×' + v.h); }
        t.appendChild(el('div', 'vname', name));
        t.appendChild(el('div', 'vsub', bits.join(' · ')));
        t.appendChild(sizeLine(v.path));
        return t;
    }

    /* on-disk size under the resolution row: KB under 1 MB, else MB. A HEAD
       request answers without downloading (the carrier sheets are 12-14 MB
       each and these tiles are in a sidebar — we must never pull the body
       just to print a number); only if the server withholds content-length
       do we fall back to a GET. Results memoise per asset. */
    var sizeCache = {};                   // asset url -> bytes (null = n/a)
    function sizeLine(path) {
        var url = 'assets/' + path;
        var d = el('div', 'vsize');
        function put(b) {
            sizeCache[url] = b;
            d.textContent = b == null ? 'size n/a'
                : b < 1048576 ? Math.max(1, Math.round(b / 1024)) + ' KB'
                : (b / 1048576).toFixed(1) + ' MB';
        }
        if (sizeCache[url] !== undefined) {
            put(sizeCache[url]);
        } else {
            d.textContent = '\u2026';
            fetch(url, { method: 'HEAD' }).then(function (r) {
                var n = r.ok && r.headers.get('content-length');
                if (n) { return +n; }
                return fetch(url).then(function (r2) {
                    return r2.blob();
                }).then(function (bl) { return bl.size; });
            }).then(function (bytes) {
                put(bytes);
            }).catch(function () { put(null); });
        }
        return d;
    }

    function el(tag, cls, text) {
        var n = document.createElement(tag);
        if (cls) { n.className = cls; }
        if (text != null) { n.textContent = text; }
        return n;
    }

    /* ---- bsv3 named-anim filmstrip player ----------------------------------
       v = {kind:'anim', path, name, frames, cols, cellw, cellh, fps}. The
       atlas (web/assets/city/anims/) packs one anchor-centred frame per cell;
       we draw one cell at a time onto a canvas sized to the cell (capped for
       the sidebar). bsv3 encodes no frame timing, so playback speed is a
       choice — the ⏩ button cycles 1x / 2x / 4x of the 12 fps default. */
    var MAX_W = 160, MAX_H = 140;      // cell display cap in the sidebar

    function animTile(v) {
        var t = el('div', 'vtile anim');
        t.dataset.tip = 'bsv3 animation \u201c' + v.name + '\u201d \u00b7 ' +
            v.frames + ' frames \u00b7 ' + v.cellw + '\u00d7' + v.cellh +
            ' \u2014 click to play/pause, \u23e9 cycles speed';
        var cv = document.createElement('canvas');
        var s = Math.min(1, MAX_W / v.cellw, MAX_H / v.cellh);
        cv.width = Math.max(1, Math.round(v.cellw * s));
        cv.height = Math.max(1, Math.round(v.cellh * s));
        cv.className = 'vcv';
        t.appendChild(cv);
        t.appendChild(el('div', 'vname', v.name));
        t.appendChild(el('div', 'vsub',
            'anim \u00b7 ' + v.frames + ' f \u00b7 bsv3'));
        t.appendChild(sizeLine(v.path));
        var bar = el('div', 'vbar');
        var play = el('button', 'on', '\u23f8');
        var fast = el('button', null, '\u23e9 1\u00d7');
        bar.appendChild(play);
        bar.appendChild(fast);
        t.appendChild(bar);

        var ctx = cv.getContext('2d');
        var img = new Image();
        var st = { i: 0, t: 0, raf: null, playing: true, rate: 1, last: 0 };

        function draw() {
            if (!img.complete || !img.naturalWidth) { return; }
            ctx.clearRect(0, 0, cv.width, cv.height);
            ctx.imageSmoothingEnabled = s < 1;
            if (v.sub) {
                // sparse shelf (tools/gen_city_sprites.py): the frame is a
                // list of rects, each blitted from the packed (sx,sy) spot
                // to the cell coord (ox+ax, oy+ay) — mirrors animOf/sparse
                // blitting in city-view-pixi.js
                var rs = v.sub[st.i] || [];
                var ax = v.ax || 0, ay = v.ay || 0;
                for (var j = 0; j < rs.length; j++) {
                    var r = rs[j];
                    ctx.drawImage(img, r.sx, r.sy, r.w, r.h,
                                  (r.ox + ax) * s, (r.oy + ay) * s,
                                  r.w * s, r.h * s);
                }
                return;
            }
            var col = st.i % v.cols, row = Math.floor(st.i / v.cols);
            ctx.drawImage.apply(ctx, [img]
                .concat([col * v.cellw, row * v.cellh, v.cellw, v.cellh])
                .concat([0, 0, cv.width, cv.height]));
        }
        function frame(now) {
            st.raf = requestAnimationFrame(frame);
            if (!st.playing) { st.last = now; return; }
            if (!st.last) { st.last = now; }
            st.t += (now - st.last) * st.rate;
            st.last = now;
            var step = 1000 / (v.fps || 12);
            while (st.t >= step) {
                st.t -= step;
                st.i = (st.i + 1) % v.frames;
                draw();
            }
        }
        img.onload = function () { draw(); };
        img.src = 'assets/' + v.path;
        if (img.complete) { draw(); }
        st.raf = requestAnimationFrame(frame);

        play.addEventListener('click', function (ev) {
            ev.stopPropagation();
            st.playing = !st.playing;
            play.textContent = st.playing ? '\u23f8' : '\u25b6';
            play.classList.toggle('on', st.playing);
        });
        fast.addEventListener('click', function (ev) {
            ev.stopPropagation();
            st.rate = st.rate >= 4 ? 1 : st.rate * 2;
            fast.textContent = '\u23e9 ' + st.rate + '\u00d7';
        });
        t.addEventListener('click', function () {
            st.playing = !st.playing;
            play.textContent = st.playing ? '\u23f8' : '\u25b6';
            play.classList.toggle('on', st.playing);
        });

        players.push({ stop: function () { cancelAnimationFrame(st.raf); } });
        return t;
    }

    global.AssetVariants = { render: renderVariants, stop: stopPlayers };
})(window);
