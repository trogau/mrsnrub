/* pb-layout.js — Byte Map page logic (2026-10-19).
   Drill-down stacked bars over window.PBLAYOUT (generated by
   tools/gen_pb_layout.py): row 0 splits the whole city save by top-level
   LandMessage field; clicking a segment opens its interior; colours =
   how far our RE has reached (decoded / partial / schema-only / unknown).
   Static data, opens from file://. */
(function () {
'use strict';

var D = window.PBLAYOUT;

function $(id) { return document.getElementById(id); }
function esc(s) {
    return String(s == null ? '' : s).replace(/[&<>"]/g, function (c) {
        return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c];
    });
}
function fmt(n) { return n == null ? '' : Number(n).toLocaleString('en-US'); }
function hex(n) { return '0x' + n.toString(16); }
function pct(size, total) { return total ? (100 * size / total) : 0; }
function label(seg) {
    return seg.n || ('field ' + seg.f);
}
function tip(seg, total) {
    var t = label(seg) + ' · f' + seg.f + ' ' + seg.wt +
        ' · ' + fmt(seg.size) + ' B (' + pct(seg.size, total).toFixed(2) + '%)' +
        (seg.cnt > 1 ? ' · ×' + fmt(seg.cnt) + (seg.agg ? ' occurrences (aggregate)' : '') : '') +
        ' · ' + hex(seg.off) + '–' + hex(seg.end);
    if (seg.det) { t += ' · ' + detSummary(seg.det); }
    if (seg.note) {
        var n = seg.note;
        if (n.length > 80) {
            n = n.split(' — ')[0];
            if (n.length > 80) { n = n.slice(0, 77) + '…'; }
        }
        t += ' · ' + n;
    }
    return t;
}

/* ---- TerrainData grid analysis (codebook verified in notes/01) ------------ */

function detSummary(det) {
    if (Array.isArray(det)) {
        return det.length + ' grid layers (' + det[0].ttn + '…' +
            det[det.length - 1].ttn + ')';
    }
    return (det.ttn || 'grid') + ' grid · ' + fmt(det.tiles) +
        ' tiles (' + det.fill + '%)';
}
function maskHex(m) {
    return m === null ? '—' : '0x' + ('0000' + m.toString(16)).slice(-4).toUpperCase();
}
function charMeaning(m) {
    if (m === null) { return 'decoder ignores (unknown char)'; }
    if (m === 0) { return 'empty — no tiles'; }
    if (m === 0xFFFF) { return 'all 16 tiles (2-unit)'; }
    return '1 tile @ x=' + Math.round(Math.log(m) / Math.LN2);
}
function detBlock(x) {
    var bits = [];
    if (x.ttn) { bits.push('terrainType <b>' + esc(x.ttn) + '</b> (' + x.tt + ')'); }
    if (x.hid != null) { bits.push('header.id ' + x.hid); }
    if (x.mds != null) {
        bits.push('mapDataSize ' + fmt(x.mds) +
            (x.sizeOk === true ? ' = len ✓'
                : x.sizeOk === false ? ' ≠ len ' + fmt(x.len) + ' ✗' : ''));
    }
    if (x.bn) { bits.push('brush <b>' + esc(x.bn) + '</b> — ' + esc(x.bs)); }
    var h = '<dt>grid analysis</dt><dd>' + bits.join(' · ') + '<br>' +
        fmt(x.tiles) + ' / ' + fmt(x.tileTotal) + ' tiles filled (' +
        x.fill + '%) · non-empty chars ' + fmt(x.nonG) +
        (x.unknown ? ' · <span class="warn">' + fmt(x.unknown) +
            ' decoder-ignored</span>' : '') + '</dd>';
    h += '<dt>char histogram — 1 char = 16 tiles</dt><dd class="hist">';
    var max = x.hist.length ? x.hist[0].n : 1;
    x.hist.forEach(function (r) {
        var w = Math.max(1, Math.round(100 * Math.log(r.n + 1) /
            Math.log(max + 1)));
        h += '<div class="hr"' + (r.m === null
            ? ' data-tip="not in the verified a..p/G/P codebook"' : '') + '>' +
            '<span class="hc">' + esc(r.c) + '</span>' +
            '<span class="hm">' + maskHex(r.m) + '</span>' +
            '<span class="hn">' + fmt(r.n) + '</span>' +
            '<i class="hb" style="width:' + w + '%"></i>' +
            '<span class="hx' + (r.m === null ? ' warn' : '') + '">' +
            charMeaning(r.m) + '</span></div>';
    });
    h += '</dd>';
    h += '<dt>tile map</dt><dd><canvas id="gc0" class="gcanvas"></canvas>' +
        '<div class="dim">' + esc(x.wn || '') + '</div></dd>';
    if (x.runs && x.runs.length) {
        h += '<dt>first filled chars</dt><dd class="sample">' +
            x.runs.map(function (r) {
                return '#' + fmt(r[0]) + ' ' + esc(r[1]);
            }).join('  ') + '</dd>';
    }
    return h;
}
function detHtml(det) {
    if (Array.isArray(det)) {
        var h = '<dt>grid layers (' + det.length + ')</dt><dd class="hist">';
        det.forEach(function (x, i) {
            h += '<div class="hr"><canvas id="gct' + i +
                '" class="gthumb" width="64" height="20"></canvas>' +
                '<span class="hc">' +
                esc(x.ttn || ('tt' + x.tt)) + '</span>' +
                '<span class="hn">' + fmt(x.tiles) + ' tiles</span>' +
                '<i class="hb" style="width:' +
                Math.max(1, Math.min(100, Math.round(x.fill * 10))) +
                '%"></i><span class="hx">' + x.fill + '% · ' + fmt(x.nonG) +
                ' non-empty chars' + (x.bn ? ' · brush ' + esc(x.bn) +
                ' (' + esc(x.bs) + ')' : '') + '</span></div>';
        });
        return h + '</dd>';
    }
    return detBlock(det);
}

/* stack levels: {seg: parent segment|null, kids: [...], total: bytes} */
var stack = [];
var pinned = null;

function statusCounts() {
    var b = D.byStatus, tot = D.topBytes || D.size, parts = [];
    [['decoded', 'decoded'], ['partial', 'partial'],
     ['schema', 'schema-only'], ['unknown', 'unknown']].forEach(function (p) {
        var v = b[p[0]] || 0;
        if (v) { parts.push(p[1] + ' ' + (100 * v / tot).toFixed(1) + '%'); }
    });
    return parts.join(' · ');
}

function renderHead() {
    $('fileinfo').textContent = D.file + ' — ' + fmt(D.size) + ' bytes · ' +
        D.fields + ' top-level fields · sha256 ' + D.sha256 + '…';
    $('statsbar').textContent = statusCounts();
    $('legend').innerHTML = [
        ['decoded', 'var(--ok)', 'we parse and use this content'],
        ['partial', 'var(--warn)', 'structure understood / partially decoded'],
        ['schema', '#3d5a7a', 'name known from the compiled proto only'],
        ['unknown', 'var(--err)', 'not in the extracted schema'],
    ].map(function (p) {
        return '<span data-tip="' + esc(p[2]) + '"><i class="sw st-' + p[0] +
            '" style="background:' + p[1] + '"></i>' + p[0] + '</span>';
    }).join('');
}

function renderCrumbs() {
    var host = $('crumbs');
    host.innerHTML = '';
    stack.forEach(function (lv, i) {
        if (i > 0) {
            var sep = document.createElement('span');
            sep.className = 'sep';
            sep.textContent = '›';
            host.appendChild(sep);
        }
        var a = document.createElement(lv.kids.length || i === stack.length - 1
            ? 'a' : 'a');
        a.textContent = lv.seg ? label(lv.seg) : 'LandMessage';
        if (i === stack.length - 1) { a.className = 'cur'; }
        a.addEventListener('click', function () {
            stack = stack.slice(0, i + 1);
            render();
        });
        host.appendChild(a);
    });
}

function renderRuler() {
    var host = $('ruler');
    host.innerHTML = '';
    var lv = stack[stack.length - 1];
    var lo = lv.seg ? lv.seg.off : 0;
    var hi = lv.seg ? lv.seg.end : D.size;
    for (var i = 0; i <= 10; i++) {
        var s = document.createElement('span');
        s.style.left = (i * 10) + '%';
        s.textContent = hex(lo + Math.round((hi - lo) * i / 10));
        host.appendChild(s);
    }
}

function segEl(seg, total, depth, levelIdx) {
    var el = document.createElement('div');
    el.className = 'seg st-' + (seg.st || 'unknown');
    el.style.width = Math.max(pct(seg.size, total), 0.15) + '%';
    el.setAttribute('data-tip', tip(seg, total));
    var p = pct(seg.size, total);
    if (p >= 2.2) {
        var l = document.createElement('span');
        l.className = 'lbl';
        l.textContent = label(seg) +
            (p >= 6 ? ' ' + (p >= 50 ? p.toFixed(0) : p.toFixed(1)) + '%' : '');
        el.appendChild(l);
    }
    el.addEventListener('mouseenter', function () { renderPane(seg, total); });
    el.addEventListener('click', function () {
        pinned = seg;
        stack = stack.slice(0, levelIdx + 1);
        if (seg.kids && seg.kids.length) {
            stack.push({ seg: seg, kids: seg.kids, total: seg.size });
        }
        render();
    });
    return el;
}

function renderRows() {
    var host = $('rows');
    host.innerHTML = '';
    stack.forEach(function (lv, i) {
        var row = document.createElement('div');
        row.className = 'brow l' + Math.min(i, 3);
        if (!lv.kids || !lv.kids.length) {
            var e = document.createElement('div');
            e.className = 'empty';
            e.textContent = 'no parsed interior (raw bytes / string)';
            row.appendChild(e);
        } else {
            lv.kids.forEach(function (k) {
                row.appendChild(segEl(k, lv.total, i, i));
            });
        }
        host.appendChild(row);
    });
}

/* ---- 2-D tile map render ----------------------------------------------------
   One char = a horizontal 16-tile run, bit k = tile x-offset k (bit 0 left)
   — so the char grid draws straight to pixels. Main layers are 32 chars
   wide (512 tiles x 1087 rows, verified in notes/01); bundle roadmaps carry
   explicit sizes; anything else uses the labelled best guess. */

var LAYER_COLORS = {
    ROADS: [200, 160, 76], RIVERS: [106, 169, 217], OCEAN: [42, 111, 176],
    DIRT: [138, 107, 69], DIRT_ROADS: [160, 128, 85],
    COBBLESTONE: [153, 153, 153], ICERIVER: [159, 212, 232],
    KLSROAD: [176, 106, 217], GOLDROAD: [244, 208, 63], SAND: [217, 192, 122],
    PAVEMENT: [190, 190, 170], _default: [200, 160, 76],
};

function drawGridTo(cv, x, maxW) {
    var s = (D.grids && x.g != null) ? D.grids[x.g] : null;
    if (!s || !cv || !cv.getContext) { return false; }
    var w = x.w || 32;
    var TW = w * 16;
    var rows = Math.ceil(s.length / w);
    var sc = (maxW && TW > maxW) ? maxW / TW : 1;
    cv.width = Math.max(1, Math.round(TW * sc));
    cv.height = Math.max(1, Math.round(rows * sc));
    var ctx = cv.getContext('2d');
    if (!ctx || !ctx.createImageData) { return false; }
    var img = ctx.createImageData(cv.width, cv.height);
    var d = img.data;
    var col = LAYER_COLORS[x.ttn] || LAYER_COLORS._default;
    for (var i = 0; i < s.length; i++) {
        var c = s.charCodeAt(i);
        var m;
        if (c >= 97 && c <= 112) { m = 1 << (c - 97); }      // a..p
        else if (c === 80) { m = 0xFFFF; }                    // P
        else if (c === 71) { continue; }                      // G = empty
        else { m = -1; }                                      // ignored char
        var cx = i % w;
        var py = Math.floor(Math.floor(i / w) * sc);
        if (py >= cv.height) { continue; }
        if (m === -1) {
            var pr = Math.floor(cx * 16 * sc);
            if (pr < cv.width) { setpx(d, cv.width, pr, py, 217, 100, 89); }
            continue;
        }
        for (var k = 0; k < 16; k++) {
            if (!(m & (1 << k))) { continue; }
            var px = Math.floor((cx * 16 + k) * sc);
            if (px < cv.width) { setpx(d, cv.width, px, py, col[0], col[1], col[2]); }
        }
    }
    ctx.putImageData(img, 0, 0);
    return true;
}
function setpx(d, W, x, y, r, g, b) {
    var p = (y * W + x) * 4;
    d[p] = r; d[p + 1] = g; d[p + 2] = b; d[p + 3] = 255;
}
function drawMaps(seg) {
    if (!seg.det) { return; }
    var one = Array.isArray(seg.det) ? seg.det[0] : seg.det;
    var main = document.getElementById('gc0');
    if (main) { drawGridTo(main, one); }
    if (Array.isArray(seg.det)) {
        seg.det.forEach(function (x, i) {
            var t = document.getElementById('gct' + i);
            if (t) { drawGridTo(t, x, 64); }
        });
    }
}

function renderPane(seg, total) {
    if (!seg) { return; }
    var h = '';
    h += '<dl>';
    if (seg.note) {
        h += '<dt>overview</dt><dd class="ov">' + esc(seg.note) + '</dd>';
    }
    h += '<dt>field</dt><dd><b>' + esc(label(seg)) + '</b> &nbsp;' +
         '<span class="badge st-' + esc(seg.st || 'unknown') + '">' +
         esc(seg.st || 'unknown') + '</span></dd>';
    h += '<dt>number / wire type</dt><dd>' + seg.f + ' / ' + esc(seg.wt) +
         (seg.cnt > 1 ? ' &nbsp;(' + fmt(seg.cnt) + ' occurrences' +
             (seg.agg ? ', sizes aggregated' : '') + ')' : '') + '</dd>';
    h += '<dt>bytes</dt><dd>' + fmt(seg.size) + ' B &nbsp;(' +
         pct(seg.size, total).toFixed(3) + '% of this row)</dd>';
    h += '<dt>file span</dt><dd>' + hex(seg.off) + ' – ' + hex(seg.end) +
         '</dd>';
    if (seg.det) { h += detHtml(seg.det); }
    if (seg.sample) {
        h += '<dt>string sample</dt><dd class="sample">' + esc(seg.sample) +
             '</dd>';
    }
    if (seg.kids && seg.kids.length) {
        h += '<dt>interior</dt><dd>' + seg.kids.length +
             ' subfields — click to drill in</dd>';
    }
    h += '</dl>';
    $('pane-body').innerHTML = h;
    drawMaps(seg);
}

function render() {
    renderHead();
    renderCrumbs();
    renderRuler();
    renderRows();
    if (pinned) {
        var lv = stack[stack.length - 1];
        renderPane(pinned, lv.total);
    }
}

document.addEventListener('keydown', function (ev) {
    if (ev.key === 'Escape' && stack.length > 1) {
        stack = stack.slice(0, -1);
        pinned = stack[stack.length - 1].seg;
        render();
    }
});

if (!D) {
    $('rows').innerHTML = '<div class="brow"><div class="empty">js/' +
        'pb-layout-data.js missing — run: python3 tools/gen_pb_layout.py' +
        '</div></div>';
    $('statsbar').textContent = 'no data';
} else {
    stack = [{ seg: null, kids: D.root, total: D.size }];
    render();
}
})();
